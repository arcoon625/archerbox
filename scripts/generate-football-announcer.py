"""Offline asset preparation. The model and Python runtime never ship to players.

Use an isolated environment with kokoro-onnx 0.6.1, soundfile and ffmpeg.
Download model/voice files from the official kokoro-onnx model-files-v1.1 release.
See docs/football-broadcast.md for provenance and the reproducible command.
"""
import argparse
import hashlib
import json
import pathlib
import subprocess
import tempfile
import time

import numpy as np
import onnxruntime as rt
import soundfile as sf
from kokoro_onnx import Kokoro

parser = argparse.ArgumentParser()
parser.add_argument("--model", required=True)
parser.add_argument("--voices", required=True)
parser.add_argument("--voice", default="am_michael")
parser.add_argument("--threads", type=int, default=4)
parser.add_argument("--ffmpeg", default="ffmpeg")
parser.add_argument("--shard-index", type=int, default=0)
parser.add_argument("--shard-count", type=int, default=1)
parser.add_argument("--manifest", help="Optional JSON checkpoint for parallel offline preparation")
args = parser.parse_args()
if not 0 <= args.shard_index < args.shard_count:
    parser.error("shard-index must be less than shard-count")
root = pathlib.Path(__file__).resolve().parents[1]
lines = json.loads((root / "scripts/data/football-studio-lines.json").read_text())
out = root / "public/games/touchdown-rush/audio/announcer"
out.mkdir(parents=True, exist_ok=True)
manifest_path = out.parents[1] / "studio-clips.js"
options = rt.SessionOptions()
options.intra_op_num_threads = args.threads
options.inter_op_num_threads = 1
started = time.time()
session = rt.InferenceSession(args.model, sess_options=options, providers=["CPUExecutionProvider"])
kokoro = Kokoro.from_session(session, args.voices)
print("Model ready", round(time.time() - started, 1), "seconds", flush=True)
manifest = {}
total = sum(map(len, lines.values()))
count = 0
first = ["touchdown", "interception", "firstDown", "fieldGood", "intro", "handoff", "dropback", "sneak", "catch", "tackle"]
for category_index, kind in enumerate(first + [k for k in lines if k not in first]):
    if category_index % args.shard_count != args.shard_index:
        continue
    texts = lines[kind]
    manifest[kind] = []
    for text in texts:
        count += 1
        digest = hashlib.sha256((args.voice + "|1.07|" + text).encode()).hexdigest()[:14]
        name = f"{kind}-{digest}.mp3"
        target = out / name
        if not target.exists():
            tick = time.time()
            samples, rate = kokoro.create(text, voice=args.voice, speed=1.07, lang="en-us")
            if not np.isfinite(samples).all() or np.max(np.abs(samples)) < 0.01:
                raise ValueError("Invalid or silent audio: " + text)
            with tempfile.TemporaryDirectory(prefix="archerbox-announcer-") as tmp:
                wav = pathlib.Path(tmp) / "call.wav"
                sf.write(wav, samples, rate)
                subprocess.run([args.ffmpeg, "-y", "-hide_banner", "-loglevel", "error", "-i", str(wav),
                                "-af", "loudnorm=I=-18:TP=-2:LRA=7", "-ar", "24000", "-ac", "1",
                                "-codec:a", "libmp3lame", "-b:a", "80k", str(target)], check=True)
            print(f"{count}/{total} {kind} {len(samples)/rate:.2f}s rendered {time.time()-tick:.1f}s", flush=True)
        # Validate cached files too. ffprobe is adjacent to the supplied ffmpeg.
        probe = str(pathlib.Path(args.ffmpeg).with_name("ffprobe")) if "/" in args.ffmpeg else "ffprobe"
        seconds = float(subprocess.check_output([probe, "-v", "error", "-show_entries", "format=duration",
                                                "-of", "default=noprint_wrappers=1:nokey=1", str(target)], text=True))
        if not 0.4 < seconds < 12 or target.stat().st_size < 2000:
            raise ValueError("Invalid clip: " + str(target))
        manifest[kind].append({"text": text, "file": "audio/announcer/" + name, "duration": round(seconds, 3)})
    # A checkpoint is useful for interrupted generation; publication checks require all categories.
    data = json.dumps(manifest, ensure_ascii=False, separators=(",", ":"))
    if args.manifest:
        pathlib.Path(args.manifest).write_text(data)
    else:
        manifest_path.write_text("// Generated by scripts/generate-football-announcer.py. See docs/football-broadcast.md.\n"
                                "export const STUDIO_CLIPS=" + data + ";\n")
print(f"Complete: {sum(map(len, manifest.values()))} clips, {time.time()-started:.1f} seconds", flush=True)
